CREATE TABLE clients (
    id VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    discount_percentage NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT pk_clients PRIMARY KEY (id),
    CONSTRAINT uk_clients_phone UNIQUE (phone)
);

CREATE TABLE cars (
    vin VARCHAR(17) NOT NULL,
    make VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    car_year INT NOT NULL,
    owner_id VARCHAR(64) NOT NULL,
    CONSTRAINT pk_cars PRIMARY KEY (vin),
    CONSTRAINT fk_cars_owner FOREIGN KEY (owner_id) REFERENCES clients (id)
);

CREATE TABLE mechanics (
    id VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    specialization VARCHAR(32) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_mechanics PRIMARY KEY (id)
);

CREATE TABLE spare_parts (
    code VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    manufacturer VARCHAR(255) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT pk_spare_parts PRIMARY KEY (code)
);

CREATE TABLE repair_orders (
    id VARCHAR(64) NOT NULL,
    car_vin VARCHAR(17) NOT NULL,
    mechanic_id VARCHAR(64),
    status VARCHAR(32) NOT NULL,
    CONSTRAINT pk_repair_orders PRIMARY KEY (id),
    CONSTRAINT fk_repair_orders_car FOREIGN KEY (car_vin) REFERENCES cars (vin),
    CONSTRAINT fk_repair_orders_mechanic FOREIGN KEY (mechanic_id) REFERENCES mechanics (id)
);

CREATE TABLE work_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    repair_order_id VARCHAR(64) NOT NULL,
    description VARCHAR(255) NOT NULL,
    labor_cost NUMERIC(10, 2) NOT NULL,
    required_specialization VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT pk_work_items PRIMARY KEY (id),
    CONSTRAINT fk_work_items_repair_order FOREIGN KEY (repair_order_id) REFERENCES repair_orders (id) ON DELETE CASCADE
);

CREATE TABLE work_item_parts (
    work_item_id BIGINT NOT NULL,
    spare_part_code VARCHAR(64) NOT NULL,
    CONSTRAINT pk_work_item_parts PRIMARY KEY (work_item_id, spare_part_code),
    CONSTRAINT fk_wip_work_item FOREIGN KEY (work_item_id) REFERENCES work_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_wip_spare_part FOREIGN KEY (spare_part_code) REFERENCES spare_parts (code)
);

CREATE INDEX idx_cars_owner ON cars (owner_id);
CREATE INDEX idx_repair_orders_car ON repair_orders (car_vin);
CREATE INDEX idx_repair_orders_mechanic ON repair_orders (mechanic_id);
CREATE INDEX idx_work_items_repair_order ON work_items (repair_order_id);
